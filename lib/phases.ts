// ─────────────────────────────────────────────────────────────
// 단계별 생성 파라미터 (temperature 차등)
// ─────────────────────────────────────────────────────────────
//
// 리서치/메타데이터처럼 정확성이 중요한 단계는 낮게,
// 창작(인트로·초안)처럼 다양성이 중요한 단계는 높게 설정한다.

export const STEP_TEMPERATURE: Record<number, number> = {
  1: 0.8, // 주제 브레인스토밍
  2: 0.3, // 딥리서치(팩트) — 정확성 우선 + 그라운딩
  3: 0.8, // 화자 프로필
  4: 0.6, // 시놉시스 구조 설계
  5: 0.9, // 인트로 후킹 — 창의성
  6: 0.9, // 초안 — 창의성
  7: 0.7, // 정밀 퇴고 — 통제된 개선
  8: 0.4, // 메타데이터 — 정확성
};

export function tempFor(step: number): number {
  return STEP_TEMPERATURE[step] ?? 0.8;
}
