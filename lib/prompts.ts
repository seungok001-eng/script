/**
 * 떡밥 원장 갱신 프롬프트 — 모듈 생성 직후 호출하는 경량 메타 작업.
 * 산문이 아니라 압축 불릿으로 원장을 다시 출력하여 크기를 일정하게 유지한다.
 */
export function buildLedgerUpdatePrompt(
  currentLedger: string,
  newChapters: string,
  chapterPair: [number, number],
): string {
  const [a, b] = chapterPair;
  return `[떡밥 원장 갱신 — 메타 작업]
주의: 이것은 대본 집필이 아니다. 아래 지시대로 '원장'만 갱신해 출력하라. 대본 본문을 절대 쓰지 마라.

[기존 원장]
${currentLedger || "(없음)"}

[방금 완성된 챕터 ${a}–${b} 본문]
${newChapters}

위 본문을 읽고 기존 원장을 갱신하여 '갱신된 원장 전체'를 아래 형식의 간결한 불릿으로 다시 출력하라.
## 미회수 떡밥
- 챕터N: (내용 한 줄) — 회수 예정: 챕터M(있으면)
## 회수 완료
- 챕터N에서 회수: (내용 한 줄)
## 핵심 설정(일관성 유지)
- (고유명사/수치/관계 등 한 줄)

규칙: 기존 미회수 항목 중 이번 본문에서 회수된 것은 '회수 완료'로 옮긴다. 새로 심긴 떡밥은 '미회수'에 추가한다. 불릿은 짧게 유지하고 중복을 제거하라.`;
}

/** 7단계(정밀 퇴고) 스트리밍 프롬프트 — 2개 챕터씩 정밀 수정 */
export function buildStep7Prompt(
  state: ScriptProjectState,
  chapterPair: [number, number],
  draftPair: string,
  userGuide: string,
): string {
  const [a, b] = chapterPair;
  return `[7단계 · 시청지속시간 극대화 정밀 퇴고 (스트리밍)]
대상 챕터: [챕터 ${a}] 와 [챕터 ${b}]

[해당 챕터 초안]
${draftPair}

위 초안을 시청지속시간(Retention) 극대화 관점에서 정밀 퇴고하라.
- 늘어지는 설명은 강렬한 비유로 압축한다.
- 다만 분량을 억지로 줄이지 말고, 고품질 구간은 그대로 보존한다(유연한 퇴고).
- 절대 규칙 1, 2, 3을 재점검하여 위반 사항을 교정한다.
- [챕터 ${a}] / [챕터 ${b}] 머리말 마커와 챕터 종료 시 줄바꿈 2번 형식을 유지한다.
- 메타 설명 없이 퇴고된 대본 본문만 출력하라.
${userGuide ? `\n[작업자 추가 가이드]\n${userGuide}` : ""}`;
}

export function buildStep8Prompt(state: ScriptProjectState, userGuide: string): string {
  const fullScript = Object.keys(state.finalChapters)
    .map(Number)
    .sort((x, y) => x - y)
    .map((k) => state.finalChapters[k])
    .join("\n\n");

  return `[8단계 · 메타데이터 출력]
확정 주제: "${state.topic}"

[최종 완성 대본 (요약 참고용 — 앞부분 발췌)]
${fullScript.slice(0, 6000)}

위 대본을 바탕으로 유튜브 업로드용 필수 메타데이터 6종을 아래 형식 그대로 출력하라.

## 1. 영상 설명
(SEO 최적화된 설명문)

## 2. 키워드 20개
(쉼표로 구분된 20개)

## 3. 제목 후보 20개
1) ...
... 20) ...

## 4. 썸네일 문구 20개
1) ...
... 20) ...

## 5. 출처
(대본에 인용된 팩트의 출처 목록)

## 6. 퀴즈 2개
Q1. ... / 정답: ...
Q2. ... / 정답: ...
${userGuide ? `\n[작업자 추가 가이드]\n${userGuide}` : ""}`;
}
