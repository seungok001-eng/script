// 1단계 주제 발굴 입력 루트: 키워드 / 레퍼런스 대본 / AI 자율 발굴
export type TopicMode = "keyword" | "reference" | "auto";

export function buildStep1Prompt(
  mode: TopicMode,
  input: string,
  userGuide: string,
): string {
  const today = new Date().toLocaleString("ko-KR", {
    dateStyle: "full",
    timeStyle: "short",
  });

  const target: Record<TopicMode, string> = {
    keyword: `사용자가 제시한 핵심 키워드를 출발점으로 삼는다.\n[키워드]\n${input}`,
    reference: `사용자가 제시한 레퍼런스 대본/콘텐츠를 먼저 분석한다. 이 레퍼런스가 다루는 핵심 주제·포맷·후킹 방식을 파악한 뒤, 같은 결로 '지금' 더 크게 터질 인접·후속·상위 주제를 발굴한다.\n[레퍼런스]\n${input}`,
    auto: `특정 입력 없이, 네가 직접 지금 이 순간 가장 뜨거운 주제를 발굴한다. 경제/안보/기술/국제정세/국뽕 카테고리에서 시의성과 조회수 폭발력이 가장 높은 소재를 스스로 선별한다.`,
  };

  return `[1단계 · 딥리서치 기반 주제 발굴]
현재 시각: ${today}

너는 지금 웹 검색(Google Search)을 가동한 유튜브 트렌드 리서처다. 단발성 검색이 아니라 가능한 한 폭넓게 다각도로 검색하여, 국내(한국)와 해외의 '현재 시각까지'의 최신 자료(뉴스, 통계, 공식 발표, 커뮤니티/SNS 반응, 경쟁 영상 동향)를 종합 조사하라.

[리서치 대상]
${target[mode]}

[임무]
조사 결과를 바탕으로, 지금 올리면 조회수가 폭발할 만한 시의성 높은 유튜브 대본 주제를 '5가지 이상' 추천하라. 모든 주제는 최신 실제 사실에 근거해야 하며(환각 금지), 왜 '지금'인지 날짜·근거와 함께 제시하라.

[각 주제 출력 형식]
## 주제 N: (강력한 한 줄 제목)
- 시의성 (왜 지금인가): 최신 사건/날짜/맥락
- 후킹 포인트 (왜 터지는가):
- 조회수 잠재력 근거: 검색·트렌드상 수요 신호
- 핵심 서사 각도:
- 예상 타깃 시청자:
- 근거 자료: 참고한 핵심 출처/지표 요약

마지막에 5개 중 조회수·몰입 잠재력이 가장 큰 주제를 골라 아래 형식으로 정확히 표기하라(파싱용).
## 추천 종합
1순위: 주제 N - (한 줄 이유)
2순위: 주제 M - (한 줄 이유)
${userGuide ? `\n[작업자 추가 가이드]\n${userGuide}` : ""}`;
}

